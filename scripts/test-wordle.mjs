async function centeredDialog(page, selector, tolerance = 1.5) {
  const box = await page.locator(selector).boundingBox();
  const viewport = page.viewportSize();
  assert.ok(box && viewport, `Missing dialog geometry for ${selector}`);
  const center = { x: box.x + box.width / 2, y: box.y + box.height / 2 };
  assert.ok(Math.abs(center.x - viewport.width / 2) <= tolerance, `${selector} x-center ${JSON.stringify({box, viewport})}`);
  assert.ok(Math.abs(center.y - viewport.height / 2) <= tolerance, `${selector} y-center ${JSON.stringify({box, viewport})}`);
  assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= viewport.width && box.y + box.height <= viewport.height, `${selector} viewport ${JSON.stringify({box, viewport})}`);
  return { box, center };
}
async function stableDialogCenter(page, selector) {
  const first = await centeredDialog(page, selector);
  await page.waitForTimeout(250);
  const settled = await centeredDialog(page, selector);
  assert.ok(Math.abs(first.center.x - settled.center.x) <= .5 && Math.abs(first.center.y - settled.center.y) <= .5, `${selector} moved while opening`);
}
