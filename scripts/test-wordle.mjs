async function fresh(width = 1280) {
  const context = await browser.newContext({ viewport: { width, height: 900 }, serviceWorkers: 'block' });
  const page = await context.newPage();
  await page.addInitScript(() => {
    globalThis.wordleWarningStacks = [];
    Error.stackTraceLimit = 28;
    const warn = console.warn;
    console.warn = (...args) => {
      if (String(args[0]).includes('STRICT_READ') && globalThis.wordleWarningStacks.length < 30) globalThis.wordleWarningStacks.push({ message: String(args[0]), stack: new Error().stack });
      warn.apply(console, args);
    };
  });
  page.on('pageerror', error => runtimeErrors.push(error.stack));
  page.on('pageerror', error => diagnostics.push(error.stack));
  page.on('console', message => { if (['warning', 'error'].includes(message.type())) diagnostics.push(message.text()); });
  for (const name of ['site.css', 'shared-runtime.js', 'favicon.svg']) await page.route(`**/${name}`, route => route.fulfill({ body: readFileSync(`docs/${name}`), contentType: name.endsWith('.css') ? 'text/css' : name.endsWith('.js') ? 'text/javascript' : 'image/svg+xml' }));
  return { context, page };
}
